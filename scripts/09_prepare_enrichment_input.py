import pandas as pd
from config import TABLE_DIR, ENRICHMENT_DIR, LOG2FC_THRESHOLD, TOP_N_ENRICHMENT

def write_gene_list(path, genes):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(genes) + "\n", encoding="utf-8")

def split_direction(df, fc_col):
    up = df[df[fc_col] > LOG2FC_THRESHOLD].sort_values(fc_col, ascending=False)
    down = df[df[fc_col] < -LOG2FC_THRESHOLD].sort_values(fc_col, ascending=True)
    return up, down

def main():
    results = pd.read_csv(TABLE_DIR / "all_genes_log2fc.csv", index_col="GeneID")
    high = pd.read_csv(TABLE_DIR / "high_vs_wt_candidate_genes.csv", index_col="GeneID")
    low = pd.read_csv(TABLE_DIR / "low_vs_wt_candidate_genes.csv", index_col="GeneID")

    high_up, high_down = split_direction(high, "High_log2FC")
    low_up, low_down = split_direction(low, "low_log2FC")
    conc_up = results[(results["low_log2FC"] > LOG2FC_THRESHOLD) & (results["High_log2FC"] > LOG2FC_THRESHOLD)]
    conc_down = results[(results["low_log2FC"] < -LOG2FC_THRESHOLD) & (results["High_log2FC"] < -LOG2FC_THRESHOLD)]
    conc_up = conc_up.sort_values("High_log2FC", ascending=False)
    conc_down = conc_down.sort_values("High_log2FC", ascending=True)

    sets = {
        "high_vs_wt_up": high_up,
        "high_vs_wt_down": high_down,
        "low_vs_wt_up": low_up,
        "low_vs_wt_down": low_down,
        "concentration_dependent_up": conc_up,
        "concentration_dependent_down": conc_down,
    }
    for name, frame in sets.items():
        write_gene_list(ENRICHMENT_DIR / f"{name}.txt", frame.index.tolist())

    combined = TABLE_DIR / "candidate_gene_lists_for_enrichment.txt"
    with combined.open("w", encoding="utf-8") as f:
        f.write("Candidate gene lists generated by fold-change screening\n")
        f.write(f"Threshold: |log2FC| > {LOG2FC_THRESHOLD}; no p-value or FDR is available\n\n")
        for name, frame in sets.items():
            f.write(f"[{name}] n={len(frame)}\n")
            preview = frame.head(TOP_N_ENRICHMENT)
            f.write(preview.to_csv(sep="\t"))
            f.write("\n")

    print(f"Saved individual gene lists to: {ENRICHMENT_DIR}")
    print(f"Saved combined list to: {combined}")
    for name, frame in sets.items():
        print(f"{name}: {len(frame)}")

if __name__ == "__main__":
    main()
